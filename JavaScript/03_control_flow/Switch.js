const month = 3
switch (month) {
    case 1: // we can use a string value in case condition if key value in string 
        console.log("January")
        break;
    case 2:
        console.log("February")
        break;
    case 3:
        console.log("March")
        break;
    case 4:
        console.log("April")
        break;

    default:
        break;
}